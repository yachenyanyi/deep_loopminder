from langchain.agents.middleware import SummarizationMiddleware
from src.models.llm import default_model


full_featured_summary = SummarizationMiddleware(
    model=default_model,
    trigger=("tokens", 30000),
    keep=("messages", 20),
    summary_prompt=(
        "你是一个编程对话上下文压缩器。请严格按照以下规则压缩对话。\n\n"
    
    "=== 核心原则 ===\n"
    "1. 忠实于原文：不要添加原文没有的信息，不要遗漏原文的关键信息\n"
    "2. 准确判断状态：根据对话内容判断任务/问题的实际状态\n"
    "3. 保留技术细节：错误类型、函数签名、配置参数必须准确\n\n"
    
    "=== 状态判断规则 ===\n"
    "- [已完成]: 对话中给出了完整实现代码\n"
    "- [已解决]: 对话中给出了明确的解决方案\n"
    "- [进行中]: 对话中正在讨论但未给出最终方案\n"
    "- [待处理]: 对话中明确提到'需要'、'待办'、'下一步'\n\n"
    
    "=== 必须保留的信息 ===\n"
    "1. 错误类型全名 (如: ImportError, requests.exceptions.ReadTimeout)\n"
    "2. 解决方案的核心代码或命令\n"
    "3. 文件名和函数签名\n"
    "4. 配置参数的具体值\n"
    "5. 设计决策的理由\n\n"
    
    "=== 可以移除的信息 ===\n"
    "1. 重复的讨论内容\n"
    "2. 失败的尝试过程 (保留失败原因和最终方案)\n"
    "3. 冗长的解释和评论\n"
    "4. 超过20行的代码 (保留签名和关键逻辑)\n\n"
    
    "=== 输入上下文 ===\n"
    "{messages}\n\n"
    
    "=== 输出格式 ===\n\n"
    "## 当前焦点\n"
    "<current_focus>\n"
    "[正在进行的任务，无则填'无']\n"
    "</current_focus>\n\n"
    
    "## 环境\n"
    "<environment>\n"
    "依赖: [列出所有依赖包]\n"
    "配置: [关键配置项]\n"
    "</environment>\n\n"
    
    "## 已完成任务\n"
    "<completed_tasks>\n"
    "| 任务 | 结果 | 状态 |\n"
    "|------|------|------|\n"
    "| [任务名] | [关键代码/结果] | 已完成 |\n"
    "</completed_tasks>\n\n"
    
    "## 已解决问题\n"
    "<resolved_issues>\n"
    "| 错误类型 | 解决方案 | 状态 |\n"
    "|----------|----------|------|\n"
    "| ImportError | pip install datasets | 已解决 |\n"
    "| ReadTimeout | timeout=300 | 已解决 |\n"
    "</resolved_issues>\n\n"
    
    "## 待解决问题\n"
    "<active_issues>\n"
    "| 问题 | 状态 | 下一步 |\n"
    "|------|------|--------|\n"
    "[仅列出明确未解决的问题]\n"
    "</active_issues>\n\n"
    
    "## 代码状态\n"
    "<code_state>\n"
    "```\n"
    "# 文件: data_loader.py [已完成]\n"
    "class DataLoader:\n"
    "    def __init__(self, dataset_name: str)\n"
    "    def load(self, split: str, num_samples: int)\n"
    "```\n"
    "</code_state>\n\n"
    
    "## 待办事项\n"
    "<pending_tasks>\n"
    "- [仅列出明确声明的待办，不要将已完成任务放入此处]\n"
    "</pending_tasks>\n\n"
    
    "## 重要上下文\n"
    "<important_context>\n"
    "- [其他关键信息]\n"
    "</important_context>"
    ),
)
